// Generates app/Support/Icons.php from the installed Font Awesome package, so
// the paths in PHP are real Font Awesome data rather than hand-copied, and
// re-running this after an upgrade picks the new ones up. `npm run icons`.
//
// The print sheet is rendered from file:// by headless Chromium, so icons have
// to be inline SVG: a webfont or a stylesheet link would not load there.
import { writeFileSync } from 'node:fs';
import * as solid from '@fortawesome/free-solid-svg-icons';

// name used in the app => Font Awesome solid icon
const MAP = {
    // The game's own symbols, written as {omen} and friends in card text.
    omen: 'faEye',
    gold: 'faCoins',
    damage: 'faBurst',
    dread: 'faSkull',
    health: 'faHeart',

    // Entity card types.
    attack: 'faHandFist',
    hazard: 'faTriangleExclamation',
    summon: 'faUsers',
    curse: 'faHandSparkles',
    story: 'faScroll',

    // Player card types.
    action: 'faBolt',
    item: 'faBox',
    response: 'faShieldHalved',

    // Where a player card starts, and what an upgrade is.
    'zone-deck': 'faLayerGroup',
    'zone-shop': 'faCartShopping',
    'zone-play': 'faStar',
    'zone-upgrade': 'faHammer',

    // Navigation and actions.
    overview: 'faHouse',
    cards: 'faClone',
    scenario: 'faGhost',
    module: 'faPuzzlePiece',
    character: 'faUser',
    rulebook: 'faBook',
    config: 'faSliders',
    print: 'faPrint',
    edit: 'faPen',
    duplicate: 'faCopy',
    'delete': 'faTrash',
    add: 'faPlus',
    warning: 'faTriangleExclamation',
    hand: 'faHand',
    beat: 'faBookOpen',
    board: 'faChessRook',
    town: 'faShop',
};

const missing = Object.entries(MAP).filter(([, fa]) => !solid[fa]);
if (missing.length) {
    console.error('Not in Font Awesome free solid:', missing.map(([, fa]) => fa).join(', '));
    process.exit(1);
}

const rows = Object.entries(MAP).map(([name, fa]) => {
    const [width, height, , , path] = solid[fa].icon;
    // A couple of icons ship their path as an array of two sub-paths.
    const d = Array.isArray(path) ? path.join(' ') : path;

    return `        '${name}' => ['fa' => '${solid[fa].iconName}', 'w' => ${width}, 'h' => ${height}, 'd' => '${d}'],`;
});

const version = JSON.parse(
    (await import('node:fs')).readFileSync(
        new URL('../node_modules/@fortawesome/free-solid-svg-icons/package.json', import.meta.url),
        'utf8'
    )
).version;

writeFileSync(
    new URL('../app/Support/Icons.php', import.meta.url),
    `<?php

namespace App\\Support;

/**
 * The app's icons, as inline SVG.
 *
 * GENERATED by build/icons.mjs from Font Awesome Free ${version}. Edit the map
 * in that script and run \`npm run icons\`, don't edit this file.
 *
 * Inline SVG rather than a webfont because the print sheet is rendered from
 * file:// by headless Chromium, where a font or stylesheet link would not load.
 * The same markup goes to the browser through Inertia's shared props, so the
 * editor and the printed card show the same icon by construction.
 *
 * Font Awesome Free icons are CC BY 4.0: https://fontawesome.com/license/free
 */
class Icons
{
    /** name => Font Awesome icon name, viewBox size and path data. */
    public const PATHS = [
${rows.join('\n')}
    ];

    /** True when an icon of this name exists. */
    public static function has(string $name): bool
    {
        return isset(self::PATHS[$name]);
    }

    /**
     * One icon as an inline <svg>. It inherits the surrounding colour and sizes
     * itself off the surrounding font, so it sits in text like a character.
     */
    public static function svg(string $name, string $class = 'icon'): string
    {
        $icon = self::PATHS[$name] ?? null;

        if ($icon === null) {
            return '';
        }

        return sprintf(
            '<svg class="%s" viewBox="0 0 %d %d" xmlns="http://www.w3.org/2000/svg" fill="currentColor" aria-hidden="true" focusable="false"><path d="%s"/></svg>',
            e($class),
            $icon['w'],
            $icon['h'],
            $icon['d'],
        );
    }

    /** Everything the browser needs to draw the same icons. */
    public static function forBrowser(): array
    {
        return self::PATHS;
    }
}
`
);

console.log(`app/Support/Icons.php — ${rows.length} icons from Font Awesome Free ${version}`);
